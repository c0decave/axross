@pytest.mark.parametrize("mode", [0o640, 0o604, 0o644, 0o660, 0o606])
def test_sad_a_key_readable_by_others_is_refused(files, key, mode):
    key_file, sums = files
    key_file.chmod(mode)
    done = run("--allow-unpinned", key_file, sums)
    assert done.returncode != 0
    assert "readable by group or others" in done.stderr
    assert not sums.with_name("SHA256SUMS.sig").exists()
    no_key_material(done.stdout + done.stderr, key, key_file)


def test_sad_an_unpinned_key_is_refused_without_the_flag(files, key):
    key_file, sums = files
    done = run(key_file, sums)
    assert done.returncode != 0
    assert "not pinned" in done.stderr and public_key_b64(key) in done.stderr
    assert not sums.with_name("SHA256SUMS.sig").exists()


def test_sad_a_key_that_is_not_ed25519_is_refused(tmp_path, files):
    _key_file, sums = files
    other = write_key(tmp_path / "ec.pem", ec.generate_private_key(ec.SECP256R1()))
    done = run("--allow-unpinned", other, sums)
    assert done.returncode != 0 and "Ed25519" in done.stderr
    assert not sums.with_name("SHA256SUMS.sig").exists()


def test_sad_a_garbage_key_file_is_refused_without_echoing_it(tmp_path, files):
    _key_file, sums = files
    garbage = tmp_path / "garbage.pem"
    garbage.write_text("<REDACTED-PRIVATE-KEY>\n")
    garbage.chmod(0o600)
    done = run("--allow-unpinned", garbage, sums)
    assert done.returncode != 0 and "cannot read the private key" in done.stderr
    assert "SECRETSECRETSECRET" not in done.stdout + done.stderr
    assert not sums.with_name("SHA256SUMS.sig").exists()


def test_sad_a_wrong_passphrase_is_refused(tmp_path, key, monkeypatch, capsys):
    key_file = write_key(tmp_path / "k.pem", key, password=b"right")
    sums = tmp_path / "SHA256SUMS"
    sums.write_bytes(SUMS_TEXT)
    monkeypatch.setattr(sign_release.getpass, "getpass", lambda prompt="": "wrong")
