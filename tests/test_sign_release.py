"""scripts/sign_release.py: the signing step of a release (docs/PACKAGING.md).

It writes SHA256SUMS.sig - the raw 64-byte Ed25519 signature of the exact
bytes of SHA256SUMS - next to SHA256SUMS. Every key here is generated by
the test; the real release key is never read.
"""

from __future__ import annotations

import base64
import hashlib
import os
import subprocess
import sys
from pathlib import Path

import pytest
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "sign_release.py"
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import sign_release  # noqa: E402

from core import self_update as SU  # noqa: E402
from tests.fake_github import (  # noqa: E402
    FakeGitHub,
    FakeHttpsHandler,
    FakeRelease,
    newer_than,
    public_key_b64,
)

DIGEST = hashlib.sha256(b"binary").hexdigest()
SUMS_TEXT = f"{DIGEST}  axross-full\n{DIGEST}  axross-slim\n".encode()


def raw_private(key: Ed25519PrivateKey) -> bytes:
    return key.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                             serialization.NoEncryption())


def write_key(path: Path, key, *, mode=0o600, password: bytes | None = None) -> Path:
    encryption = (serialization.BestAvailableEncryption(password) if password
                  else serialization.NoEncryption())
    pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                            encryption)
    path.write_bytes(pem)
    path.chmod(mode)
    return path


@pytest.fixture
def key():
    return Ed25519PrivateKey.generate()


@pytest.fixture
def files(tmp_path, key):
    key_file = write_key(tmp_path / "release.pem", key)
    dist = tmp_path / "dist"
    dist.mkdir()
    sums = dist / "SHA256SUMS"
    sums.write_bytes(SUMS_TEXT)
    return key_file, sums


def run(*args, env=None):
    return subprocess.run([sys.executable, str(SCRIPT), *map(str, args)], capture_output=True,
                          text=True, timeout=60, env=env, cwd=ROOT)


def no_key_material(output: str, key: Ed25519PrivateKey, key_file: Path) -> None:
    raw = raw_private(key)
    assert raw.hex() not in output.lower()
    assert base64.b64encode(raw).decode() not in output
    for line in key_file.read_text().splitlines():
        if line and not line.startswith("-----"):
            assert line not in output


# --- happy -----------------------------------------------------------------------------


def test_happy_cli_signs_and_the_updater_verifies(files, key):
    key_file, sums = files
    done = run("--allow-unpinned", key_file, sums)
    assert done.returncode == 0, done.stderr
    sig = sums.with_name("SHA256SUMS.sig")
    assert sig.read_bytes() and len(sig.read_bytes()) == SU.SIG_BYTES
    SU.verify_signature(SUMS_TEXT, sig.read_bytes(), keys=(public_key_b64(key),))
    assert public_key_b64(key) in done.stdout  # the PUBLIC key is named, for checking
    no_key_material(done.stdout + done.stderr, key, key_file)
    assert sig.stat().st_mode & 0o777 == 0o644


def test_happy_a_pinned_key_needs_no_flag(files, key, monkeypatch, capsys):
    key_file, sums = files
    monkeypatch.setattr(SU, "TRUSTED_KEYS", (public_key_b64(key),))
    assert sign_release.main([str(key_file), str(sums)]) == 0
    SU.verify_signature(SUMS_TEXT, sums.with_name("SHA256SUMS.sig").read_bytes())
    out = capsys.readouterr()
    assert "pinned" in out.out
    no_key_material(out.out + out.err, key, key_file)


def test_happy_e2e_a_release_signed_by_the_script_updates(files, key, tmp_path, monkeypatch):
    """The script's output, served as the release's SHA256SUMS.sig, is what
    an installed binary accepts."""
    from axross._version import __version__

    new_bytes = b"\x7fELF new" * 3000
    release = FakeRelease(newer_than(__version__), {"axross-full": new_bytes})
    key_file, sums = files
    sums.write_bytes(release.sums_text().encode())
    monkeypatch.setattr(SU, "TRUSTED_KEYS", (public_key_b64(key),))
    assert sign_release.main([str(key_file), str(sums)]) == 0
    release.sig_override = sums.with_name("SHA256SUMS.sig").read_bytes()
    exe = tmp_path / "axross-full"
    exe.write_bytes(b"old")
    exe.chmod(0o755)
    inst = SU.detect_install(frozen=True, executable=str(exe), bundle_dir=None,
                             platform="linux", machine="x86_64")
    with FakeGitHub(release) as server:
        opener = SU.build_opener(handlers=[FakeHttpsHandler(server.port)])
        found = SU.check(opener=opener).release
        assert SU.update(found, inst, opener=opener).replaced
    assert exe.read_bytes() == new_bytes


def test_happy_an_encrypted_key_asks_for_its_passphrase(tmp_path, key, monkeypatch, capsys):
    key_file = write_key(tmp_path / "k.pem", key, password=b"correct horse")
    sums = tmp_path / "SHA256SUMS"
    sums.write_bytes(SUMS_TEXT)
    monkeypatch.setattr(sign_release.getpass, "getpass", lambda prompt="": "correct horse")
    assert sign_release.main(["--allow-unpinned", str(key_file), str(sums)]) == 0
    SU.verify_signature(SUMS_TEXT, (tmp_path / "SHA256SUMS.sig").read_bytes(),
                        keys=(public_key_b64(key),))
    out = capsys.readouterr()
    assert "correct horse" not in out.out + out.err


