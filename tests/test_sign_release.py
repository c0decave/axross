def test_sad_a_signature_that_does_not_verify_is_never_written(files, key, monkeypatch,
                                                                 capsys):
    key_file, sums = files
    monkeypatch.setattr(sign_release, "sign", lambda private_key, data: b"\0" * 64)
    assert sign_release.main(["--allow-unpinned", str(key_file), str(sums)]) != 0
    assert "does not verify" in capsys.readouterr().err
    assert not sums.with_name("SHA256SUMS.sig").exists()


# --- edge ------------------------------------------------------------------------------


@pytest.mark.parametrize("content", [b"", b"no checksum lines here\n",
                                     b"x" * (SU.MAX_SUMS_BYTES + 1)],
                         ids=["empty", "no-entries", "oversized"])
def test_edge_a_sums_file_the_updater_would_refuse_is_not_signed(files, content):
    key_file, sums = files
    sums.write_bytes(content)
    done = run("--allow-unpinned", key_file, sums)
    assert done.returncode != 0 and "SHA256SUMS" in done.stderr
    assert not sums.with_name("SHA256SUMS.sig").exists()


def test_edge_an_old_signature_is_replaced_atomically(files, key):
    key_file, sums = files
    sig = sums.with_name("SHA256SUMS.sig")
    sig.write_bytes(b"stale")
    assert run("--allow-unpinned", key_file, sums).returncode == 0
    SU.verify_signature(SUMS_TEXT, sig.read_bytes(), keys=(public_key_b64(key),))
    assert sorted(p.name for p in sums.parent.iterdir()) == ["SHA256SUMS", "SHA256SUMS.sig"]


def test_edge_a_symlinked_key_file_is_refused(tmp_path, files):
    key_file, sums = files
    link = tmp_path / "link.pem"
    os.symlink(key_file, link)
    done = run("--allow-unpinned", link, sums)
    assert done.returncode != 0 and "regular file" in done.stderr
    assert not sums.with_name("SHA256SUMS.sig").exists()


def test_edge_the_signature_covers_the_exact_bytes(files, key):
    """CRLF line ends or a missing final newline are signed as they are -
    nothing is normalised."""
    key_file, sums = files
    exact = SUMS_TEXT.replace(b"\n", b"\r\n").rstrip(b"\n")
    sums.write_bytes(exact)
    assert run("--allow-unpinned", key_file, sums).returncode == 0
    sig = sums.with_name("SHA256SUMS.sig").read_bytes()
    SU.verify_signature(exact, sig, keys=(public_key_b64(key),))
    with pytest.raises(SU.SignatureError):
        SU.verify_signature(SUMS_TEXT, sig, keys=(public_key_b64(key),))
