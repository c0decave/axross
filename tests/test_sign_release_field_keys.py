"""scripts/sign_release.py refuses a key the binaries in use do not trust.

0.15.176 pins a second release key but shipped no binaries; every installed
binary (0.14.136 and older) pins only the first key. A release signed with
the second key would be refused by all of them, so sign_release.py signs
only with a key of FIELD_KEYS unless --allow-new-key is given (with a
warning). Every key here is generated by the test.
"""

from __future__ import annotations

import hashlib
import subprocess
import sys
from pathlib import Path

import pytest
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import sign_release  # noqa: E402

from core import self_update as SU  # noqa: E402
from tests.fake_github import public_key_b64  # noqa: E402

DIGEST = hashlib.sha256(b"binary").hexdigest()
SUMS = f"# axross-release 9.9.9\n{DIGEST}  axross-full\n".encode()


def write_key(path: Path, key: Ed25519PrivateKey) -> Path:
    path.write_bytes(key.private_bytes(serialization.Encoding.PEM,
                                       serialization.PrivateFormat.PKCS8,
                                       serialization.NoEncryption()))
    path.chmod(0o600)
    return path


@pytest.fixture
def rotation(tmp_path, monkeypatch):
    """The state of 0.15.176: two pinned keys, the binaries in use trust the
    first one only."""
    old, new = Ed25519PrivateKey.generate(), Ed25519PrivateKey.generate()
    monkeypatch.setattr(SU, "TRUSTED_KEYS", (public_key_b64(old), public_key_b64(new)))
    monkeypatch.setattr(sign_release, "FIELD_KEYS", (public_key_b64(old),))
    sums = tmp_path / "SHA256SUMS"
    sums.write_bytes(SUMS)
    return (write_key(tmp_path / "old.pem", old), write_key(tmp_path / "new.pem", new), sums,
            public_key_b64(old), public_key_b64(new))


def test_happy_the_field_key_signs_without_a_flag_or_warning(rotation, capsys):
    old_file, _new_file, sums, old_pub, _new_pub = rotation
    assert sign_release.main([str(old_file), str(sums)]) == 0
    SU.verify_signature(SUMS, sums.with_name("SHA256SUMS.sig").read_bytes(), keys=(old_pub,))
    assert "WARNING" not in capsys.readouterr().err


def test_sad_the_new_key_is_refused_without_the_override(rotation, capsys):
    _old_file, new_file, sums, _old_pub, new_pub = rotation
    assert sign_release.main([str(new_file), str(sums)]) == 1
    err = capsys.readouterr().err
    assert new_pub in err and "FIELD_KEYS" in err and "--allow-new-key" in err
    assert not sums.with_name("SHA256SUMS.sig").exists()
    assert sums.read_bytes() == SUMS


def test_sad_allow_unpinned_does_not_let_the_new_key_through(rotation):
    """--allow-unpinned is for a key the tree does not pin; the new key is
    pinned, the field-key refusal still holds."""
    _old_file, new_file, sums, _old_pub, _new_pub = rotation
    assert sign_release.main(["--allow-unpinned", str(new_file), str(sums)]) == 1
    assert not sums.with_name("SHA256SUMS.sig").exists()


def test_happy_the_override_signs_with_a_warning_and_the_field_refuses_it(rotation, capsys):
    _old_file, new_file, sums, old_pub, new_pub = rotation
    assert sign_release.main(["--allow-new-key", str(new_file), str(sums)]) == 0
    assert "WARNING" in capsys.readouterr().err
    sig = sums.with_name("SHA256SUMS.sig").read_bytes()
    SU.verify_signature(SUMS, sig, keys=(new_pub,))
    with pytest.raises(SU.SignatureError):  # what an installed 0.14.136 does with it
        SU.verify_signature(SUMS, sig, keys=(old_pub,))


def test_sad_the_cli_refuses_a_key_outside_the_field(tmp_path):
    """Through the real script: the release keys of the tree, a throwaway
    key - not pinned, not in the field."""
    key_file = write_key(tmp_path / "k.pem", Ed25519PrivateKey.generate())
    sums = tmp_path / "SHA256SUMS"
    sums.write_bytes(SUMS)
    done = subprocess.run([sys.executable, str(ROOT / "scripts" / "sign_release.py"),
                           str(key_file), str(sums)], capture_output=True, text=True, timeout=60,
                          cwd=ROOT)
    assert done.returncode == 1 and "not pinned" in done.stderr
    help_text = subprocess.run([sys.executable, str(ROOT / "scripts" / "sign_release.py"), "-h"],
                               capture_output=True, text=True, timeout=60, cwd=ROOT).stdout
    assert "--allow-new-key" in help_text


def test_edge_field_keys_are_pinned_keys():
    assert sign_release.FIELD_KEYS
    assert set(sign_release.FIELD_KEYS) <= set(SU.TRUSTED_KEYS)


def test_edge_field_keys_are_what_the_last_release_with_binaries_pins():
    """0.14.136 is the newest release with binaries (0.15.176 has none):
    FIELD_KEYS is what it pins. Change FIELD_KEYS only together with this
    test, when a release with binaries pinning the new key is out."""
    shown = subprocess.run(["git", "show", "v0.14.136:core/self_update.py"], cwd=ROOT,
                           capture_output=True, text=True, timeout=60)
    if shown.returncode != 0:
        pytest.skip("no git history with the tag v0.14.136 (an sdist, a shallow clone)")
    namespace: dict = {}
    start = shown.stdout.index("TRUSTED_KEYS: tuple[str, ...] = ")
    end = shown.stdout.index(")", start) + 1
    exec(shown.stdout[start:end].replace(": tuple[str, ...]", ""), namespace)  # noqa: S102
    assert tuple(sign_release.FIELD_KEYS) == tuple(namespace["TRUSTED_KEYS"])


def test_edge_the_docs_name_the_condition_for_the_new_key():
    text = (ROOT / "docs" / "PACKAGING.md").read_text(encoding="utf-8")
    assert "the release after it is signed with the new key" not in text
    assert "FIELD_KEYS" in text and "--allow-new-key" in text
