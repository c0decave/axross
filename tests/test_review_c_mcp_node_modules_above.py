"""Review C, round 1: the ``node_modules`` folders above a host-run Node
server's folder.

Node looks a ``require('x')`` / ``import 'x'`` up in ``node_modules`` of
the script's folder, then of every folder above it. The pin and the write
guard (core.mcp_script_pin) held the server's folder only: an agent whose
root held ``~/proj`` wrote ``~/proj/node_modules/bufferutil/index.js`` (a
module ``ws`` and many others ``require`` when it is there), and the
server ran it with the user's rights at its next start - no pin noticed
it, nothing asked. In a monorepo that is where all the server's packages
are (hoisted to the repository's ``node_modules``).

Now the agent writes, creates, moves and removes nothing in a
``node_modules`` folder above a host-run Node server's folder.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from core import mcp_client as C  # noqa: E402
from core import mcp_runner as R  # noqa: E402
from core import mcp_script_pin as PIN  # noqa: E402
from core import protected_places as P  # noqa: E402
from core.agent_settings import AgentSettings  # noqa: E402

PYTHON = os.path.realpath(sys.executable)


@pytest.fixture
def home(tmp_path, monkeypatch):
    home = tmp_path / "home"
    home.mkdir()
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setenv("XDG_STATE_HOME", str(home / ".local" / "state"))
    monkeypatch.delenv(P.HOST_HOME_ENV, raising=False)
    monkeypatch.setattr(R, "launcher_place_problem", lambda *a, **k: "")
    PIN._GUARD_CACHE.clear()
    yield home
    PIN._GUARD_CACHE.clear()


@pytest.fixture
def folder(home):
    folder = home / "proj" / "packages" / "srv"
    folder.mkdir(parents=True)
    (folder / "server.js").write_text("try { require('bufferutil') } catch (e) {}\n")
    return folder


def _saved(*configs):
    settings = AgentSettings()
    settings.mcp_servers = list(configs)
    settings.save()
    PIN._GUARD_CACHE.clear()
    return AgentSettings.load().mcp_servers


def _js(folder, name="js") -> C.McpServerConfig:
    return C.McpServerConfig(name=name, command=("/usr/bin/node", str(folder / "server.js")))


@pytest.mark.parametrize("above", ["packages", "."])
def test_sad_a_module_above_a_node_servers_folder_is_refused_to_the_agent(folder, home, above):
    _saved(_js(folder))
    base = (home / "proj" / above).resolve()
    planted = base / "node_modules" / "bufferutil" / "index.js"
    refused = P.refusal(str(planted))
    assert refused and "'js'" in refused
    assert P.refusal(str(base / "node_modules"), entry=True)
    assert P.refusal(str(base / "node_modules" / "bufferutil"), entry=True)


def test_sad_a_symlinked_way_to_the_folder_above_counts_too(folder, home):
    os.symlink(home / "proj", home / "work")
    _saved(_js(folder))
    assert P.refusal(str(home / "work" / "node_modules" / "x" / "index.js"))


def test_happy_the_rest_of_the_folders_above_stay_writable(folder, home):
    _saved(_js(folder))
    for path in (home / "proj" / "README.md", home / "proj" / "packages" / "other" / "a.js",
                 home / "proj" / "packages" / "other" / "node_modules" / "x.js",
                 home / "proj" / "node_modules_notes.txt"):
        assert P.refusal(str(path)) is None, path


def test_happy_a_python_server_leaves_node_modules_above_alone(home):
    folder = home / "proj" / "srv"
    folder.mkdir(parents=True)
    (folder / "server.py").write_text("print(1)\n")
    _saved(C.McpServerConfig(name="py", command=(PYTHON, str(folder / "server.py"))))
    assert P.refusal(str(home / "proj" / "node_modules" / "x" / "index.js")) is None


def test_happy_a_switched_off_node_server_guards_nothing(folder, home):
    off = _js(folder)
    off.enabled = False
    _saved(off)
    assert P.refusal(str(home / "proj" / "node_modules" / "x" / "index.js")) is None


@pytest.mark.skipif(not shutil.which("node"), reason="no node here")
def test_edge_node_does_load_a_module_from_a_folder_above(tmp_path):
    """Why: the resolution the guard is about, shown with the real node."""
    srv = tmp_path / "proj" / "srv"
    srv.mkdir(parents=True)
    (srv / "server.js").write_text(
        "try { require('bufferutil'); } catch (e) { console.log('none'); }\n")
    planted = tmp_path / "proj" / "node_modules" / "bufferutil"
    planted.mkdir(parents=True)
    (planted / "index.js").write_text("console.log('planted ran');\n")
    out = subprocess.run([shutil.which("node"), str(srv / "server.js")], capture_output=True,
                         text=True, timeout=30, cwd=str(tmp_path))
    assert "planted ran" in out.stdout
